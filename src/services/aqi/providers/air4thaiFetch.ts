const REQUEST_TIMEOUT_MS = 30_000;

// Built once: Node's default roots plus the two missing Let's Encrypt certificates.
const trustedCAs: string[] = [...tls.rootCertificates, LETS_ENCRYPT_YR1, ISRG_ROOT_YR];

/**
 * GETs an Air4Thai JSON endpoint over HTTPS with the extra CA trust described above.
 * Uses node:https because the global fetch cannot take a per-request CA list.
 * Throws on network errors, timeouts, non-2xx statuses and invalid JSON, so callers can
 * treat it exactly like the shared fetchJson helper.
 */
export function fetchAir4ThaiJson(url: string): Promise<unknown> {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { ca: trustedCAs, timeout: REQUEST_TIMEOUT_MS }, (res) => {
      const status = res.statusCode ?? 0;
      if (status < 200 || status >= 300) {
        res.resume(); // discard the body so the socket is released
        reject(new Error(`Request failed: ${url} with status ${status}`));
        return;
      }

      const chunks: Buffer[] = [];
      res.on("data", (chunk: Buffer) => chunks.push(chunk));
      res.on("error", reject);
      res.on("end", () => {
        try {
          resolve(JSON.parse(Buffer.concat(chunks).toString("utf8")));
        } catch (err) {
          reject(err instanceof Error ? err : new Error(String(err)));
        }
      });
    });

    req.on("timeout", () => req.destroy(new Error(`Request timed out: ${url}`)));
    req.on("error", reject);
  });
}
